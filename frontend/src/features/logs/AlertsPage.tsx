const FACILITY_OPTIONS = Object.entries(LOG_FACILITY_LABEL)
  .filter(([key]) => key !== 'UNKNOWN')
  .map(([value, label]) => ({ value, label }));

function formatTimestamp(value: string): string {
  try {
    return new Date(value).toLocaleString(undefined, {
      month: 'short',
      day: '2-digit',
      hour: '2-digit',
      minute: '2-digit',
      second: '2-digit',
    });
  } catch {
    return value;
  }
}

