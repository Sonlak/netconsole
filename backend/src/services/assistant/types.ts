/**
 * Type definitions for the AI Assistant.
 *
 * The LLM (gpt-4.1-mini) is stateless — every request re-sends the
 * full message history. We mirror OpenAI's Chat Completions shape so
 * the wire format stays simple, then add a thin wrapper for the
 * NetConsole-specific bits (confirmation_required, tool role).
 */

import type { ChatCompletionMessageParam } from 'openai/resources/chat/completions';

/** Re-export of OpenAI's message shape for clarity. */
export type AssistantMessage = ChatCompletionMessageParam;

/**
 * A `tool` role message paired with its parent `assistant` tool_call.
 * The OpenAI wire format stores the tool_call_id only on the result
 * row; we keep the name too so the frontend can render the call
 * without re-parsing the assistant message.
 */
export type AssistantToolMessage = Extract<AssistantMessage, { role: 'tool' }>;

